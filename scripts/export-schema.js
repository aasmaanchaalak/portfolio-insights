// Writes scripts/schema.sql: the current database's structure (tables,
// constraints, indexes, sequences, functions) with no data. A new firm's
// database is created from it with scripts/setup-db.js.
//
//   node scripts/export-schema.js            # reads DATABASE_URL from .env.local
//
// Re-run after adding a migration so schema.sql stays current.

const fs = require('fs');
const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '..', '.env.local'), quiet: true });
const { Pool } = require('pg');

const url = process.env.DATABASE_URL;
if (!url) { console.error('DATABASE_URL is not set'); process.exit(1); }
const pool = new Pool({ connectionString: url, ssl: /localhost/.test(url) ? false : { rejectUnauthorized: false } });

const q = async (sql) => (await pool.query(sql)).rows;
const ident = (s) => (/^[a-z_][a-z0-9_]*$/.test(s) ? s : `"${s.replace(/"/g, '""')}"`);

(async () => {
  const out = [
    '-- Generated by scripts/export-schema.js. Structure only, no data.',
    '-- Apply to an empty database with: node scripts/setup-db.js <DATABASE_URL>',
    '',
  ];

  const seqs = await q(`
    SELECT s.sequencename AS name, s.data_type, s.start_value, s.increment_by,
           d.refobjid::regclass::text AS owner_table, a.attname AS owner_col
    FROM pg_sequences s
    JOIN pg_class c ON c.relname = s.sequencename
    JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = s.schemaname
    LEFT JOIN pg_depend d ON d.objid = c.oid AND d.deptype = 'a'
    LEFT JOIN pg_attribute a ON a.attrelid = d.refobjid AND a.attnum = d.refobjsubid
    WHERE s.schemaname = 'public' ORDER BY 1`);
  for (const s of seqs) {
    out.push(`CREATE SEQUENCE ${ident(s.name)} AS ${s.data_type} START ${s.start_value} INCREMENT ${s.increment_by};`);
  }
  if (seqs.length) out.push('');

  const tables = (await q(`
    SELECT c.oid, c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY c.relname`));

  const fks = [];
  for (const t of tables) {
    const cols = await q(`
      SELECT a.attname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull,
             pg_get_expr(d.adbin, d.adrelid) AS def, a.attidentity
      FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE a.attrelid = ${t.oid} AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`);
    const cons = await q(`
      SELECT conname, contype, pg_get_constraintdef(oid) AS def FROM pg_constraint
      WHERE conrelid = ${t.oid} ORDER BY contype, conname`);

    const lines = cols.map((c) => {
      let l = `  ${ident(c.attname)} ${c.type}`;
      if (c.attidentity === 'a') l += ' GENERATED ALWAYS AS IDENTITY';
      else if (c.attidentity === 'd') l += ' GENERATED BY DEFAULT AS IDENTITY';
      else if (c.def != null) l += ` DEFAULT ${c.def}`;
      if (c.attnotnull) l += ' NOT NULL';
      return l;
    });
    for (const c of cons) {
      if (c.contype === 'f') fks.push(`ALTER TABLE ${ident(t.relname)} ADD CONSTRAINT ${ident(c.conname)} ${c.def};`);
      else if (c.contype !== 'n') lines.push(`  CONSTRAINT ${ident(c.conname)} ${c.def}`);
    }
    out.push(`CREATE TABLE ${ident(t.relname)} (\n${lines.join(',\n')}\n);`, '');
  }

  for (const s of seqs) {
    if (s.owner_table) out.push(`ALTER SEQUENCE ${ident(s.name)} OWNED BY ${s.owner_table}.${ident(s.owner_col)};`);
  }
  if (fks.length) out.push('', ...fks);

  const idx = await q(`
    SELECT indexdef FROM pg_indexes i
    WHERE schemaname = 'public' AND NOT EXISTS (
      SELECT 1 FROM pg_constraint c WHERE c.conname = i.indexname AND c.contype IN ('p', 'u', 'x'))
    ORDER BY tablename, indexname`);
  out.push('', ...idx.map((i) => `${i.indexdef};`));

  const fns = await q(`
    SELECT pg_get_functiondef(p.oid) AS def FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
    WHERE n.nspname = 'public' ORDER BY p.proname`);
  for (const f of fns) out.push('', `${f.def.trim()};`);

  const trg = await q(`
    SELECT pg_get_triggerdef(t.oid) AS def FROM pg_trigger t
    JOIN pg_class c ON c.oid = t.tgrelid JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND NOT t.tgisinternal ORDER BY 1`);
  if (trg.length) out.push('', ...trg.map((t) => `${t.def};`));

  const file = path.join(__dirname, 'schema.sql');
  fs.writeFileSync(file, out.join('\n') + '\n');
  console.log(`Wrote ${file}: ${tables.length} tables, ${idx.length} indexes, ${fks.length} foreign keys, ${fns.length} functions`);
  await pool.end();
})().catch((e) => { console.error(e.message); process.exit(1); });
